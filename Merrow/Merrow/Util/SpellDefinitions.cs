    public class SpellText
    {
        public SpellNameEnum SpellEnum { get; private set; }

        public string RomNameAddress { get; private set; }
        public string[] NamePrefixes { get; private set;  }
        public string SpellItemDescription { get; private set; }

        private string adjectiveA;
        private string adjectiveB;
        private string nounA; 
        private string nounB; 
        private string romAddressNameValue;
        private string romAddressNamePointer;
        private string ramUpdatedPointer;
        private string itemText;

        private SpellText temporaryOverrideText;

        public SpellText(SpellNameEnum spellEnum, string adjA, string adjB, string nounA, string nounB, string romAddrNameValue, string romAddrNamePtr, string ramUpdatedPtr)
        {
            this.SpellEnum = spellEnum;
            this.adjectiveA = adjA;
            this.adjectiveB = adjB;
            this.nounA = nounA;
            this.nounB = nounB;

            this.romAddressNameValue = romAddrNameValue;
            this.romAddressNamePointer = romAddrNamePtr;
            this.ramUpdatedPointer = ramUpdatedPtr;

            this.itemText = "UNASSIGNED";
        }

        public void OverrideText(SpellText overridingSpell)
        {
            this.temporaryOverrideText = overridingSpell;
        }

        public void ClearOverride()
        {
            this.temporaryOverrideText = null;
        }

        public string[] GetTextInfo()
        {
            if (this.temporaryOverrideText != null)
            {
                var overrideInfo = this.temporaryOverrideText.GetTextInfo();

                return new string[]
                {
                    overrideInfo[0],
                    overrideInfo[1],
                    overrideInfo[2],
                    overrideInfo[3],
                    this.romAddressNameValue,
                    this.romAddressNamePointer,
                    this.ramUpdatedPointer
                };
            }

            return new string[]
            {
                this.adjectiveA,
                this.adjectiveB,
                this.nounA,
                this.nounB,
                this.romAddressNameValue,
                this.romAddressNamePointer,
                this.ramUpdatedPointer
            };
        }
        
        public string GetItemText()
        {
            if (this.temporaryOverrideText != null)
                return this.temporaryOverrideText.GetItemText();

            return this.itemText;
        }

        public void AssignItemText(string itemText)
        {
            this.itemText = itemText;
        }
    }

